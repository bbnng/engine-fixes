"""Write src/build_profiles.inc: the layout and 4 KB block fingerprints of the analyzed game DLLs.

Usage: python tools/make_build_profiles.py "<game folder>"
The game folder must hold the analyzed Unofficial Patch 12 files (checked by SHA-256 below).
Each profile lets build_check.h accept the analyzed file or the same build edited in place by a
later patch: the same link time and section table, at most a tenth of its 4 KB blocks changed.
"""
import hashlib
import os
import struct
import sys

FILES = [  # (profile name, path inside the game folder, SHA-256 of the analyzed file)
    ('engine', r'Bin\engine.dll', '9d00b2c1e5edbad052fb0b514634ba54574666e12d1b408c46ce141d51ed2313'),
    ('material', r'Bin\MaterialSystem.dll', 'e7e694c75843c1cc2af360b3606ef55cd0558ae445c9fc087e56fdf3816cdc9b'),
    ('filesystem', r'Bin\FileSystem_Stdio.dll', 'ff69aa1ada4bcef2c5fb2277502718fb45ea0d7429f9240b9472eb62753a6194'),
    # The copy the game loads (next to Vampire.exe). Older patches load Bin\vampire_python21.dll
    # (2ce854dd...), the same build with 4 of its 173 blocks different.
    ('python', r'vampire_python21.dll', '65a92dda7b8fd1ca8668cc8924d6300a895603b719e19c3b537751e434ec4ea3'),
]


def profile(name, data):
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    count, = struct.unpack_from('<H', data, pe + 6)
    timestamp, = struct.unpack_from('<I', data, pe + 8)
    optional, = struct.unpack_from('<H', data, pe + 20)
    table = pe + 24 + optional
    sections = []
    for i in range(count):
        h = data[table + 40 * i:table + 40 * i + 40]
        size, address, raw_size, raw_offset = struct.unpack_from('<IIII', h, 8)
        label = h[:8].rstrip(b'\0').decode()
        sections.append(f'{{"{label}",0x{size:x},0x{address:x},0x{raw_size:x},0x{raw_offset:x}}}')
    blocks = [struct.unpack('<I', hashlib.sha256(data[i:i + 4096]).digest()[:4])[0] for i in range(0, len(data), 4096)]
    rows = [','.join(f'0x{b:08x}u' for b in blocks[i:i + 10]) for i in range(0, len(blocks), 10)]
    file_name = os.path.basename(FILES_BY_NAME[name][1])
    return (f'const Section {name}_sections[]={{{",".join(sections)}}};\n'
            f'const std::uint32_t {name}_blocks[{len(blocks)}]={{\n    ' + ',\n    '.join(rows) + '};\n'
            f'const Profile {name}_profile={{"{file_name}",0x{timestamp:08x}u,{name}_sections,{count},{name}_blocks,{len(blocks)}}};\n')


FILES_BY_NAME = {f[0]: f for f in FILES}
game = sys.argv[1]
out = ['// Generated by tools/make_build_profiles.py from the analyzed Unofficial Patch 12 files. Do not edit.\n',
       '// Per file: link time, section table (name, VirtualSize, VirtualAddress, SizeOfRawData,\n',
       '// PointerToRawData) and the first 4 bytes (LE) of each 4 KB block\'s SHA-256.\n']
for name, rel, sha in FILES:
    data = open(os.path.join(game, rel), 'rb').read()
    if hashlib.sha256(data).hexdigest() != sha:
        sys.exit(f'{rel} is not the analyzed file')
    out.append(f'\n// {rel.split(chr(92))[-1]} sha256 {sha}\n' + profile(name, data))
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, '..', 'src', 'build_profiles.inc'), 'w', encoding='utf-8', newline='\r\n').write(''.join(out))
print('wrote src/build_profiles.inc')
