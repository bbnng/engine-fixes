<#
.SYNOPSIS
  Writes src\client_blocks.inc: the block hashes of the analyzed client.dll, for engine_fixes.cpp.

  A client.dll that a newer Unofficial Patch edited in place (same link time and sections) is
  accepted while at most a tenth of its 4 KB blocks differ from the analyzed file. Each value is
  the first four bytes of the SHA-256 of one block (the last block may be shorter), read as a
  little-endian number.

  .\tools\Get-ClientBlocks.ps1 -ClientDll <path to the analyzed client.dll>
#>
param([Parameter(Mandatory = $true)][string]$ClientDll)
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$path = (Resolve-Path -LiteralPath $ClientDll).Path
$analyzed = 'e88beae0dd03af06493c71c5e8d87a6993b54e590cb6ad37cd3513c588582870'
$actual = (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash.ToLowerInvariant()
if ($actual -ne $analyzed) { throw "$path is not the analyzed client.dll (sha256 $actual)." }
$blockSize = 4096
$bytes = [IO.File]::ReadAllBytes($path)
$count = [int][Math]::Ceiling($bytes.Length / $blockSize)
$sha = [Security.Cryptography.SHA256]::Create()
$out = New-Object Text.StringBuilder
[void]$out.AppendLine('// Generated by tools\Get-ClientBlocks.ps1: do not edit. The first four bytes (little-endian) of the')
[void]$out.AppendLine("// SHA-256 of each $blockSize-byte block of the analyzed client.dll (sha256 e88beae0...).")
[void]$out.AppendLine("const std::uint32_t client_blocks[$count] = {")
$line = New-Object Text.StringBuilder
for ($i = 0; $i -lt $count; ++$i) {
    $offset = $i * $blockSize
    $digest = $sha.ComputeHash($bytes, $offset, [Math]::Min($blockSize, $bytes.Length - $offset))
    [void]$line.Append(('0x{0:x8}u,' -f [BitConverter]::ToUInt32($digest, 0)))
    if (($i % 10) -eq 9 -or $i -eq $count - 1) { [void]$out.AppendLine('    ' + $line.ToString()); [void]$line.Clear() }
}
[void]$out.AppendLine('};')
$target = Join-Path $root 'src\client_blocks.inc'
[IO.File]::WriteAllText($target, $out.ToString().Replace("`r`n", "`n").Replace("`n", "`r`n"), (New-Object Text.UTF8Encoding $false))
Write-Output "Wrote $target"
